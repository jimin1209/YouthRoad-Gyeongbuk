class InstitutionSummary {
  const InstitutionSummary({
    required this.instNo,
    required this.name,
  });

  final String instNo;
  final String name;
}

class DepartmentSummary {
  const DepartmentSummary({
    required this.instNo,
    required this.deptNo,
    required this.name,
  });

  final String instNo;
  final String deptNo;
  final String name;
}
